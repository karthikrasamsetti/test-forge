class TestValidationResult:
    def test_starts_valid(self) -> None:
        r = ValidationResult(filename="test.py")
        assert r.valid is True
        assert r.errors == []
        assert r.warnings == []

    def test_add_error_sets_invalid(self) -> None:
        r = ValidationResult(filename="test.py")
        r.add_error("something broke")
        assert r.valid is False
        assert "something broke" in r.errors

    def test_add_warning_keeps_valid(self) -> None:
        r = ValidationResult(filename="test.py")
        r.add_warning("minor issue")
        assert r.valid is True
        assert "minor issue" in r.warnings

    def test_multiple_errors(self) -> None:
        r = ValidationResult(filename="test.py")
        r.add_error("error 1")
        r.add_error("error 2")
        assert len(r.errors) == 2
        assert r.valid is False


