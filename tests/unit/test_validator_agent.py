class TestSyntaxCheck:
    def test_valid_source_passes(self, agent: ValidatorAgent) -> None:
        result = agent.validate_source(VALID_SOURCE)
        assert result.valid is True
        assert not any("Syntax" in e for e in result.errors)

    def test_syntax_error_detected(self, agent: ValidatorAgent) -> None:
        result = agent.validate_source(SYNTAX_ERROR_SOURCE)
        assert result.valid is False
        assert any("Syntax error" in e for e in result.errors)

    def test_empty_source_fails(self, agent: ValidatorAgent) -> None:
        # Empty file is valid Python but has no test function
        result = agent.validate_source("")
        assert not any("Syntax error" in e for e in result.errors)


