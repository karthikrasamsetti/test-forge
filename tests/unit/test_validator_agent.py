class TestValidateFile:
    def test_valid_file_passes(self, agent: ValidatorAgent, tmp_path: Path) -> None:
        f = tmp_path / "test_tc001.py"
        f.write_text(VALID_SOURCE, encoding="utf-8")
        result = agent.validate_file(str(f))
        assert result.valid is True

    def test_missing_file_is_error(self, agent: ValidatorAgent) -> None:
        result = agent.validate_file("/nonexistent/path/test_tc001.py")
        assert result.valid is False
        assert any("File not found" in e for e in result.errors)

    def test_filename_preserved(self, agent: ValidatorAgent, tmp_path: Path) -> None:
        f = tmp_path / "test_tc001_login.py"
        f.write_text(VALID_SOURCE, encoding="utf-8")
        result = agent.validate_file(str(f))
        assert result.filename == "test_tc001_login.py"

    def test_syntax_error_file(self, agent: ValidatorAgent, tmp_path: Path) -> None:
        f = tmp_path / "test_bad.py"
        f.write_text(SYNTAX_ERROR_SOURCE, encoding="utf-8")
        result = agent.validate_file(str(f))
        assert result.valid is False
        assert any("Syntax error" in e for e in result.errors)

    def test_artefact_file_invalid(self, agent: ValidatorAgent, tmp_path: Path) -> None:
        f = tmp_path / "test_artefact.py"
        f.write_text(UNPARSED_SOURCE, encoding="utf-8")
        result = agent.validate_file(str(f))
        assert result.valid is False


