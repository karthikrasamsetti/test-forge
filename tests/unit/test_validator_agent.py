class TestValidateBatch:
    def test_returns_result_for_each_file(self, agent: ValidatorAgent, tmp_path: Path) -> None:
        f1 = tmp_path / "test_tc001.py"
        f2 = tmp_path / "test_tc002.py"
        f1.write_text(VALID_SOURCE, encoding="utf-8")
        f2.write_text(VALID_SOURCE, encoding="utf-8")
        results = agent.validate_batch([str(f1), str(f2)])
        assert len(results) == 2

    def test_mixed_valid_invalid(self, agent: ValidatorAgent, tmp_path: Path) -> None:
        f1 = tmp_path / "test_good.py"
        f2 = tmp_path / "test_bad.py"
        f1.write_text(VALID_SOURCE, encoding="utf-8")
        f2.write_text(SYNTAX_ERROR_SOURCE, encoding="utf-8")
        results = agent.validate_batch([str(f1), str(f2)])
        assert results[0].valid is True
        assert results[1].valid is False

    def test_empty_list_returns_empty(self, agent: ValidatorAgent) -> None:
        results = agent.validate_batch([])
        assert results == []

    def test_all_filenames_set(self, agent: ValidatorAgent, tmp_path: Path) -> None:
        f1 = tmp_path / "test_tc001.py"
        f1.write_text(VALID_SOURCE, encoding="utf-8")
        results = agent.validate_batch([str(f1)])
        assert results[0].filename == "test_tc001.py"
