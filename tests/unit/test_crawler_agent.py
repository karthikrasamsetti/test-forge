# ── Integration tests (real browser) ──────────────────────────────────────────
@pytest.mark.integration
class TestCrawlerAgentIntegration:
    """
    Integration tests — hit real SauceDemo URL.
    Run with: pytest -m integration
    Skipped in normal CI runs.
    """

    def test_crawls_saucedemo_login_page(self):
        agent = CrawlerAgent()
        result = agent.run("https://www.saucedemo.com")
        assert result.success is True
        assert result.metadata.title != ""
        assert len(result.elements) > 0

    def test_detects_saucedemo_as_spa(self):
        agent = CrawlerAgent()
        result = agent.run("https://www.saucedemo.com")
        assert result.metadata.is_spa is True

    def test_finds_login_form_elements(self):
        agent = CrawlerAgent()
        result = agent.run("https://www.saucedemo.com")
        selectors = [e.selector for e in result.elements]
        # Should find username, password, login button
        assert any("user" in s.lower() or "username" in s.lower() for s in selectors)
        assert any("password" in s.lower() for s in selectors)

    def test_detects_auth_page(self):
        agent = CrawlerAgent()
        result = agent.run("https://www.saucedemo.com")
        assert result.metadata.has_auth is True

    def test_invalid_url_returns_failed_result(self):
        agent = CrawlerAgent()
        result = agent.run("https://this-url-does-not-exist-xyz.com")
        assert result.success is False
        assert len(result.warnings) > 0
